-- Facturas de proveedores leídas automáticamente (por n8n u otro motor) y convertidas en un borrador
-- de compra que una persona revisa antes de confirmar. Nada entra al inventario sin esa confirmación.
CREATE TABLE receipt_drafts(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id BIGINT NOT NULL REFERENCES branches,
  status VARCHAR(12) NOT NULL DEFAULT 'PENDING'
    CHECK(status IN ('PENDING','READY','FAILED','CONFIRMED','DISCARDED')),
  filename VARCHAR(200) NOT NULL,
  content_type VARCHAR(40) NOT NULL,
  size_bytes INT NOT NULL,
  supplier_id BIGINT REFERENCES suppliers,
  supplier_text VARCHAR(200) NOT NULL DEFAULT '',
  document VARCHAR(100) NOT NULL DEFAULT '',
  error VARCHAR(300) NOT NULL DEFAULT '',
  receipt_id BIGINT REFERENCES receipts,
  created_by VARCHAR(80) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX receipt_drafts_branch ON receipt_drafts(branch_id, id DESC);

-- El archivo vive en la base (cifrado en reposo si el disco lo está) para que n8n lo descargue con
-- su llave y no haya que exponer almacenamiento aparte. Se borra a los 30 días de cerrado el borrador.
CREATE TABLE invoice_files(
  draft_id BIGINT PRIMARY KEY REFERENCES receipt_drafts ON DELETE CASCADE,
  bytes BYTEA NOT NULL
);

CREATE TABLE receipt_draft_lines(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draft_id BIGINT NOT NULL REFERENCES receipt_drafts ON DELETE CASCADE,
  position INT NOT NULL,
  description VARCHAR(300) NOT NULL,
  sku VARCHAR(80) NOT NULL DEFAULT '',
  barcode VARCHAR(100) NOT NULL DEFAULT '',
  quantity NUMERIC(14,3),
  lot VARCHAR(100) NOT NULL DEFAULT '',
  expires_on DATE,
  total_cost NUMERIC(14,2),
  presentation_id BIGINT REFERENCES presentations,
  confidence NUMERIC(3,2) NOT NULL DEFAULT 0,
  method VARCHAR(12) NOT NULL DEFAULT ''
);
CREATE INDEX receipt_draft_lines_draft ON receipt_draft_lines(draft_id, position);

