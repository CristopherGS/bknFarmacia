-- Ajustes del negocio (una fila por despliegue), módulos activos, entrega de eventos a n8n y
-- llaves de API para integraciones.
CREATE TABLE settings(
  id SMALLINT PRIMARY KEY CHECK(id=1),
  business_name VARCHAR(120) NOT NULL,
  business_type VARCHAR(20) NOT NULL DEFAULT 'FARMACIA' CHECK(business_type IN ('FARMACIA','TIENDA','OTRO')),
  primary_color VARCHAR(7) NOT NULL DEFAULT '#1c765b',
  webhook_url VARCHAR(500) NOT NULL DEFAULT '',
  webhook_secret VARCHAR(100) NOT NULL DEFAULT '',
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
