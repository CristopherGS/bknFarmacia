-- El outbox pasa de marcador a cola real: cuerpo del evento, reintentos con espera y resultado.
-- Lo pendiente de antes no tenía cuerpo ni destino; se descarta para no enviar historia vieja.
UPDATE outbox_events SET status='SKIPPED' WHERE status='PENDING';
ALTER TABLE outbox_events
  ADD COLUMN payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN last_error VARCHAR(300) NOT NULL DEFAULT '',
  ADD COLUMN delivered_at TIMESTAMP WITH TIME ZONE;
CREATE INDEX outbox_pending ON outbox_events(next_attempt_at) WHERE status='PENDING';

-- Evita repetir el aviso de un lote por vencer en el mismo umbral (90 y 30 días).
CREATE TABLE expiry_alerts(
  lot_id BIGINT NOT NULL REFERENCES lots,
  threshold_days INT NOT NULL,
  alerted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(lot_id, threshold_days)
);

-- Cuentas de servicio (rol SERVICE) con llave propia para que n8n consulte el sistema.
ALTER TABLE users DROP CONSTRAINT users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check
  CHECK(role IN ('ADMIN','SUPERVISOR','CASHIER','INVENTORY','ACCOUNTANT','SERVICE'));
CREATE TABLE api_keys(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
  label VARCHAR(80) NOT NULL,
  prefix VARCHAR(16) NOT NULL,
  key_hash CHAR(64) NOT NULL UNIQUE,
  created_by VARCHAR(80) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_used_at TIMESTAMP WITH TIME ZONE,
  revoked_at TIMESTAMP WITH TIME ZONE
);
