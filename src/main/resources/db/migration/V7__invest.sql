-- Portafolio personal de ETFs. Solo existe para el dueño (variable INVEST_OWNER); en cualquier otro
-- despliegue las tablas quedan vacías y no hay ningún endpoint accesible.
CREATE TABLE invest_config(
  id SMALLINT PRIMARY KEY CHECK(id=1),
  config JSONB NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE invest_positions(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticker VARCHAR(15) NOT NULL,
  shares NUMERIC(18,6) NOT NULL CHECK(shares>0),
  avg_price_usd NUMERIC(14,4) NOT NULL CHECK(avg_price_usd>0),
  bought_on DATE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE invest_contributions(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day DATE NOT NULL,
  gtq NUMERIC(14,2) NOT NULL CHECK(gtq>0),
  usd NUMERIC(14,2) NOT NULL CHECK(usd>0),
  fx NUMERIC(10,4) NOT NULL CHECK(fx>0),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Caché de precios: el trabajo diario solo pide lo que falta y, si todas las fuentes fallan, la web
-- sigue mostrando el último dato válido con su fecha.
CREATE TABLE invest_prices(
  ticker VARCHAR(20) NOT NULL,
  day DATE NOT NULL,
  close NUMERIC(16,4) NOT NULL,
  adj_close NUMERIC(16,4) NOT NULL,
  source VARCHAR(12) NOT NULL,
  PRIMARY KEY(ticker, day)
);

CREATE TABLE invest_macro(
  series VARCHAR(20) NOT NULL,
  day DATE NOT NULL,
  value NUMERIC(14,4) NOT NULL,
  PRIMARY KEY(series, day)
);

CREATE TABLE invest_fx(
  day DATE PRIMARY KEY,
  gtq_per_usd NUMERIC(10,4) NOT NULL,
  source VARCHAR(12) NOT NULL
);

-- Un resumen calculado por día: permite ver la evolución sin recalcular el pasado.
CREATE TABLE invest_snapshots(
  day DATE PRIMARY KEY,
  data JSONB NOT NULL,
  generated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE invest_news(
  url VARCHAR(500) PRIMARY KEY,
  ticker VARCHAR(20) NOT NULL DEFAULT '',
  title VARCHAR(400) NOT NULL,
  source VARCHAR(80) NOT NULL DEFAULT '',
  published_at TIMESTAMP WITH TIME ZONE NOT NULL,
  summary VARCHAR(700) NOT NULL DEFAULT ''
);

-- Estado de las alertas para no repetirlas (último semáforo, nivel de caída avisado…).
CREATE TABLE invest_state(
  key VARCHAR(60) PRIMARY KEY,
  value VARCHAR(200) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
